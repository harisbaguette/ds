import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { asset } from './lib/illustration-store.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const readJSON = file => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
const mapping = readJSON('src/data/ui-icons.json');
const manifest = readJSON('assets/icons/illustrated/manifest.json');
const artwork = new Map(manifest.batches.flatMap(batch => batch.icons.filter(Boolean).map(item => [item.entry, item])));
const assets = {};
fs.mkdirSync(path.join(root, 'assets/icons/ui'), { recursive: true });
for (const [name, entry] of Object.entries(mapping)) {
  const item = artwork.get(manifest.aliases?.[entry] || entry);
  if (!item) throw new Error(`UI icon ${name}: missing illustration ${entry}`);
  const src = `assets/icons/ui/${name}.webp`;
  fs.writeFileSync(path.join(root, src), (await asset(entry, { size: 192 })).bytes);
  assets[name] = { entry, src };
}
const header = '// Generated by npm run build:ui-icons from src/data/ui-icons.json.\n';
fs.writeFileSync(path.join(root, 'src/ui/icons.js'), header +
  'window.Pattove.iconAssets = ' + JSON.stringify(assets, null, 2) + ';\n' +
  `window.Pattove.uiIcon = (name, extraClass = '') => {
  const asset = window.Pattove.iconAssets[name];
  if (!asset) return '';
  const classes = String(extraClass).replace(/[^a-zA-Z0-9_ -]/g, '');
  return '<img class="ui-icon' + (classes ? ' ' + classes : '') + '" src="' + asset.src + '" data-ui-icon="' + name + '" data-illustration="' + asset.entry + '" width="24" height="24" alt="" aria-hidden="true" draggable="false" decoding="async">';
};
window.Pattove.iconMarkup = Object.fromEntries(Object.keys(window.Pattove.iconAssets).map(name => [name, window.Pattove.uiIcon(name)]));
`);
// React's built-in controls carry only the individual artwork they use, including offline installs.
for (const name of ['plus', 'minus', 'close', 'image']) {
  const iconAsset = assets[name];
  const data = 'data:image/webp;base64,' + (await asset(iconAsset.entry, { size: 192 })).bytes.toString('base64');
  const component = name[0].toUpperCase() + name.slice(1) + 'Icon';
  fs.writeFileSync(path.join(root, `src/system/react/ui-icon-${name}.jsx`), header +
    `import React from 'react';\nexport function ${component}({ className = '', ...props }) { return <img width="24" height="24" alt="" aria-hidden="true" draggable={false} decoding="async" {...props} className={\`ui-icon \${className}\`} data-ui-icon="${name}" data-illustration="${iconAsset.entry}" src="${data}" />; }\n`);
}
console.log(`${Object.keys(assets).length} UI icons linked to existing illustrations.`);
