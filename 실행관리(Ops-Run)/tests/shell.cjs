const { chromium } = require('playwright-core');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const url = pathToFileURL(path.resolve(__dirname, '../index.html')).href;
const checks = [];
const check = (name, value) => { assert.ok(value, name); checks.push(name); };
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(5000);
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const count = () => page.locator('.pattern-card').count();
  const close = async () => { await page.keyboard.press('Escape'); await page.waitForFunction(() => !document.querySelector('#detail-dialog').open); };
  try {
    await page.goto(url);
    check('첫 진입은 사전 대분류', await page.locator('.dict-group').count() === 8 && page.url().includes('#/dictionary'));
    check('실제 로고 정본 로드', await page.locator('.brand img').evaluate(i => i.complete && i.naturalWidth > 0));
    await page.locator('[data-focus="page-styles"]').click();
    check('스타일에서 첫 부품 한 장으로 이동', await page.locator('.component-page[data-component="tokens"]').count() === 1 && await page.locator('.system-board').count() === 0);
    await page.goto(url + '#/patterns?style=main');
    check('선택한 스타일의 패턴 12개', await count() === 12 && await page.locator('.pattern-card .theme-main').count() === 12);
    await page.locator('[data-category="input"]').click();
    check('목적 분류로 좁히기', await count() === 2);
    check('분류에서 메인 스타일 유지', await count() === 2 && await page.locator('.pattern-card .theme-main').count() === 2);
    await page.reload();
    check('선택한 스타일과 분류 새로고침 유지', await count() === 2 && await page.locator('.pattern-card .theme-main').count() === 2);
    await page.locator('[data-category="all"]').click();
    await page.keyboard.press('/');
    check('슬래시로 검색 초점', await page.locator('#query').evaluate(e => e === document.activeElement));
    await page.locator('#query').fill('저장 완료');
    check('실제 일치 항목 제안', await page.locator('.search-suggestion').count() === 2);
    await page.locator('#query').press('ArrowUp');
    check('위 방향키로 마지막 제안 선택', await page.locator('#suggestion-1').getAttribute('aria-selected') === 'true');
    await page.locator('#query').press('Enter');
    check('제안에서 현재 스타일 상세 열림', await page.locator('#detail-dialog .preview.theme-main').count() === 1);
    await close();
    check('상세를 닫으면 검색 초점 복귀', await page.locator('#query').evaluate(e => e === document.activeElement));
    await page.locator('#query').fill('저장 완료');
    await page.locator('#query').press('Enter');
    check('검색 결과 2개', await count() === 2);
    check('현재 검색 조건 유지', await count() === 2 && await page.locator('#query').inputValue() === '저장 완료');
    await page.locator('[data-action="clear-query"]').click();
    check('검색 조건 해제', await count() === 12);
    await page.locator('[data-quick-save="tabs"]').click();
    check('카드 바로 저장', await page.locator('[data-quick-save="tabs"]').getAttribute('aria-pressed') === 'true');
    await page.reload();
    check('저장 새로고침 유지', await page.locator('[data-quick-save="tabs"]').getAttribute('aria-pressed') === 'true');
    await page.locator('[data-open="toast"]').click();
    check('상세 제목으로 초점', await page.locator('#detail-title').evaluate(e => e === document.activeElement));
    check('패턴 상세가 실제 사전과 연결됨', await page.locator('.pattern-usage').count() === 2 && await page.locator('.pattern-dictionary-link').getAttribute('href') === '#/dictionary?category=STA&detail=STA-03');
    check('상세에는 개별 스타일 변경이 없음', await page.locator('[data-detail-style]').count() === 0);
    await page.locator('[data-save="toast"]').click();
    check('상세에서 현재 스타일 저장', await page.locator('[data-save="toast"]').getAttribute('aria-pressed') === 'true');
    check('저장 후 조작 초점 유지', await page.locator('[data-save="toast"]').evaluate(e => e === document.activeElement));
    for (let i = 0; i < 10; i++) await page.keyboard.press('Tab');
    check('상세 대화상자 초점 가두기', await page.evaluate(() => !!document.activeElement.closest('dialog[open]')));
    await close();
    check('상세를 닫으면 카드로 복귀', await page.locator('[data-open="toast"]').evaluate(e => e === document.activeElement));
    await page.locator('[data-quick-save="progress"]').click();
    await page.locator('#saved-link').click();
    check('저장한 패턴은 메인 스타일로 묶음', await count() === 3 && await page.locator('.saved-group').count() === 1);
    await page.locator('#query').fill('탭');
    await page.locator('#query').press('Enter');
    check('저장한 패턴 내 검색', await count() === 1 && await page.locator('body').getAttribute('data-page') === 'saved');
    await page.locator('[data-remove="tabs"][data-style="main"]').click();
    check('저장 해제', await count() === 0);
    await page.locator('[data-action="undo-save"]').click();
    check('해제 되돌리기', await count() === 1);
    await page.reload();
    check('되돌리기 저장 유지', await count() === 1);
    await page.locator('.brand').click();
    check('로고에서 사전 첫 화면으로', await page.locator('.dict-group').count() === 8);
    await page.locator('[data-focus="page-styles"]').click();
    await page.goBack();
    check('브라우저 뒤로 가기', await page.locator('.dict-group').count() === 8);
    await page.goForward();
    check('브라우저 앞으로 가기', await page.locator('.component-page').count() === 1);
    await page.goto(url + '#/patterns?style=main');
    await page.locator('#query').fill('<img src=x onerror=alert(1)>');
    await page.locator('#query').press('Enter');
    check('검색어 HTML 미실행, 빈 결과', await count() === 0 && await page.locator('.empty-state').isVisible());
    await page.locator('[data-action="reset"]').click();
    check('빈 결과에서 복귀', await count() === 12);
    await page.goto(url + '#/patterns?style=ink&view=list&sort=name&compare=toast,tabs');
    check('옛 목록·비교 주소는 그리드로 정리', await count() === 12 && !page.url().includes('view=') && !page.url().includes('compare=') && !(await page.locator('dialog[open]').count()));
    await page.goto(url + '#/patterns?style=landscape&detail=tabs');
    check('상세 직접 주소', await page.locator('#detail-dialog').isVisible());
    await close();
    check('직접 주소를 닫아도 스타일 유지', await page.locator('.pattern-card .theme-main').count() === 12);
    const broken = await browser.newContext();
    await broken.addInitScript(() => localStorage.setItem('pattove-shell:v1', JSON.stringify({ saved: [null, {}, { id: 'missing', style: 'base' }], style: 'wrong' })));
    const brokenPage = await broken.newPage();
    await brokenPage.goto(url + '#/saved');
    check('손상된 저장 데이터 무시', await brokenPage.locator('.empty-state').isVisible());
    await broken.close();
    const blocked = await browser.newContext();
    await blocked.addInitScript(() => { Object.defineProperty(window, 'localStorage', { get() { throw new Error('blocked'); } }); });
    const blockedPage = await blocked.newPage();
    await blockedPage.goto(url + '#/patterns?style=ink');
    await blockedPage.locator('[data-quick-save="toast"]').click();
    check('저장소 차단에도 세션 저장 가능', await blockedPage.locator('[data-quick-save="toast"]').getAttribute('aria-pressed') === 'true');
    check('저장소 차단을 알려줌', (await blockedPage.locator('#notice-text').textContent()).includes('지금 열린 화면'));
    await blockedPage.locator('[data-open="tabs"]').click();
    await blockedPage.locator('[data-save="tabs"]').click();
    check('모달 안에서도 저장소 차단 표시', await blockedPage.locator('#detail-dialog .save-status').isVisible());
    await blocked.close();
    check('브라우저 오류 없음', errors.length === 0);
    fs.mkdirSync('test-results/lean', { recursive: true });
    fs.writeFileSync('test-results/lean/functional.json', JSON.stringify({ checks, errors }, null, 2));
    console.log(checks.length + ' checks passed.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });

